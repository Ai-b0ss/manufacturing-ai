-- Versioned PDF/STEP/CSV kits. Whole CZKIT1 package retains all three originals.
-- Run only after schema.sql and ingestion_v1..v3, first on scratch PostgreSQL.
BEGIN;
SET ROLE factory_owner;
SET search_path=core,pg_catalog;
CREATE TABLE core.cad_kit(
 id text PRIMARY KEY CHECK(id ~ '^kit-[0-9a-f]{32}$'),
 scope_id text NOT NULL REFERENCES core.scope(id) ON DELETE RESTRICT,
 part text NOT NULL CHECK(length(part) BETWEEN 1 AND 150),
 part_key text NOT NULL,
 latest_revision integer NOT NULL DEFAULT 0 CHECK(latest_revision BETWEEN 0 AND 10000),
 created_by text NOT NULL REFERENCES core.subject(id),
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(scope_id,part_key)
);
CREATE TABLE core.cad_kit_revision(
 id text PRIMARY KEY CHECK(id ~ '^kitrev-[0-9a-f]{32}$'),
 kit_id text NOT NULL REFERENCES core.cad_kit(id) ON DELETE RESTRICT,
 revision_no integer NOT NULL CHECK(revision_no BETWEEN 1 AND 10000),
 package bytea NOT NULL CHECK(octet_length(package) BETWEEN 13 AND 18008192),
 package_sha256 text NOT NULL CHECK(package_sha256 ~ '^[0-9a-f]{64}$'),
 report jsonb NOT NULL,
 created_by text NOT NULL REFERENCES core.subject(id),
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(kit_id,revision_no)
);
CREATE TABLE core.cad_kit_request(
 actor_id text NOT NULL REFERENCES core.subject(id),
 request_key text NOT NULL CHECK(request_key ~ '^[A-Za-z0-9_-]{16,100}$'),
 request_digest text NOT NULL CHECK(request_digest ~ '^[0-9a-f]{64}$'),
 revision_id text NOT NULL REFERENCES core.cad_kit_revision(id),
 PRIMARY KEY(actor_id,request_key)
);
CREATE INDEX cad_kit_revision_latest ON core.cad_kit_revision(kit_id,revision_no DESC);
ALTER TABLE core.cad_kit ENABLE ROW LEVEL SECURITY;
ALTER TABLE core.cad_kit FORCE ROW LEVEL SECURITY;
CREATE POLICY kit_owner ON core.cad_kit FOR ALL TO factory_owner USING(true) WITH CHECK(true);
CREATE POLICY kit_reader ON core.cad_kit FOR SELECT TO factory_gateway
 USING(core.can_read_scope(scope_id));
ALTER TABLE core.cad_kit_revision ENABLE ROW LEVEL SECURITY;
ALTER TABLE core.cad_kit_revision FORCE ROW LEVEL SECURITY;
CREATE POLICY revision_owner ON core.cad_kit_revision FOR ALL TO factory_owner USING(true) WITH CHECK(true);
CREATE POLICY revision_reader ON core.cad_kit_revision FOR SELECT TO factory_gateway
 USING(EXISTS (SELECT 1 FROM core.cad_kit k WHERE k.id=kit_id));
ALTER TABLE core.cad_kit_request ENABLE ROW LEVEL SECURITY;
ALTER TABLE core.cad_kit_request FORCE ROW LEVEL SECURITY;
CREATE POLICY request_owner ON core.cad_kit_request FOR ALL TO factory_owner USING(true) WITH CHECK(true);

-- The only CAD kit write entry point. Input report must be generated by trusted
-- analyze_bundle; stored source SHA hashes are revalidated when originals are read.
CREATE FUNCTION core.save_cad_kit_revision(
 p_key text,p_scope text,p_part text,p_kit_id text,p_expected integer,
 p_package bytea,p_report jsonb
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
DECLARE
 actor text;
 name_key text;
 fingerprint text;
 existing_digest text;
 existing_revision text;
 kit_id text;
 current_no integer;
 new_rev text;
 package_hash text;
BEGIN
 actor:=nullif(current_setting('factory.actor_id',true),'');
 IF actor IS NULL OR p_scope IS NULL OR NOT core.can_write_scope(p_scope) THEN
   RAISE EXCEPTION 'CAD_SCOPE_WRITE_DENIED' USING ERRCODE='42501';
 END IF;
 IF p_key IS NULL OR p_key !~ '^[A-Za-z0-9_-]{16,100}$'
    OR p_part IS NULL OR length(btrim(p_part)) NOT BETWEEN 1 AND 150
    OR p_part ~ '[[:cntrl:]]'
    OR p_expected IS NULL OR p_expected NOT BETWEEN 0 AND 9999
    OR (p_kit_id IS NOT NULL AND p_kit_id !~ '^kit-[0-9a-f]{32}$')
    OR p_package IS NULL OR octet_length(p_package) NOT BETWEEN 13 AND 18008192
    OR substring(p_package from 1 for 7)<>convert_to(E'CZKIT1\n','UTF8')
    OR p_report IS NULL OR p_report->>'schema'<>'factory_private_cad_bundle_v1'
    OR p_report->>'state'<>'REVIEW_REQUIRED'
    OR p_report->>'manufacturing_authorization'<>'false'
    OR p_report->>'part'<>p_part
    OR jsonb_typeof(p_report->'sources')<>'array'
    OR jsonb_array_length(p_report->'sources')<>3
    OR octet_length(convert_to(p_report::text,'UTF8'))>500000
 THEN RAISE EXCEPTION 'CAD_INPUT_INVALID' USING ERRCODE='22023'; END IF;
 package_hash:=encode(sha256(p_package),'hex');
 name_key:=lower(btrim(p_part));
 fingerprint:=encode(sha256(convert_to(
   jsonb_build_array(p_scope,name_key,p_kit_id,p_expected,package_hash,p_report)::text,
   'UTF8')),'hex');
 PERFORM pg_advisory_xact_lock(hashtextextended('cad-idem:'||actor||':'||p_key,0));
 SELECT request_digest,revision_id INTO existing_digest,existing_revision
 FROM core.cad_kit_request WHERE actor_id=actor AND request_key=p_key;
 IF FOUND THEN
   IF existing_digest<>fingerprint THEN
     RAISE EXCEPTION 'CAD_IDEMPOTENCY_CONFLICT' USING ERRCODE='23505';
   END IF;
   SELECT r.kit_id,r.revision_no INTO kit_id,current_no
   FROM core.cad_kit_revision r WHERE r.id=existing_revision;
   IF NOT EXISTS(SELECT 1 FROM core.cad_kit k WHERE k.id=kit_id AND core.can_write_scope(k.scope_id)) THEN
     RAISE EXCEPTION 'CAD_ACCESS_REVOKED' USING ERRCODE='42501';
   END IF;
   RETURN jsonb_build_object('kit_id',kit_id,'revision_id',existing_revision,
                             'revision_no',current_no,'reused',true);
 END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('cad-part:'||p_scope||':'||name_key,0));
 SELECT id,latest_revision INTO kit_id,current_no
 FROM core.cad_kit WHERE scope_id=p_scope AND part_key=name_key FOR UPDATE;
 IF NOT FOUND THEN
   IF p_expected<>0 OR p_kit_id IS NOT NULL THEN
     RAISE EXCEPTION 'CAD_KIT_MISSING' USING ERRCODE='23503';
   END IF;
   kit_id:='kit-'||replace(gen_random_uuid()::text,'-','');
   INSERT INTO core.cad_kit(id,scope_id,part,part_key,created_by)
   VALUES(kit_id,p_scope,btrim(p_part),name_key,actor);
   current_no:=0;
 ELSIF p_kit_id IS NULL OR p_kit_id<>kit_id OR p_expected<>current_no THEN
   RAISE EXCEPTION 'CAD_REVISION_CONFLICT' USING ERRCODE='23505';
 END IF;
 new_rev:='kitrev-'||replace(gen_random_uuid()::text,'-','');
 INSERT INTO core.cad_kit_revision(id,kit_id,revision_no,package,package_sha256,report,created_by)
 VALUES(new_rev,kit_id,current_no+1,p_package,package_hash,p_report,actor);
 UPDATE core.cad_kit SET latest_revision=current_no+1 WHERE id=kit_id;
 INSERT INTO core.cad_kit_request(actor_id,request_key,request_digest,revision_id)
 VALUES(actor,p_key,fingerprint,new_rev);
 INSERT INTO core.audit_event(actor,action,target,outcome)
 VALUES(actor,'save_cad_kit_revision',new_rev,'review_required');
 RETURN jsonb_build_object('kit_id',kit_id,'revision_id',new_rev,
                           'revision_no',current_no+1,'reused',false);
END;
$$;
REVOKE ALL ON core.cad_kit,core.cad_kit_revision,core.cad_kit_request FROM PUBLIC;
REVOKE ALL ON FUNCTION core.save_cad_kit_revision(text,text,text,text,integer,bytea,jsonb) FROM PUBLIC;
GRANT SELECT ON core.cad_kit,core.cad_kit_revision TO factory_gateway;
GRANT EXECUTE ON FUNCTION core.save_cad_kit_revision(text,text,text,text,integer,bytea,jsonb) TO factory_gateway;
RESET ROLE;
COMMIT;
